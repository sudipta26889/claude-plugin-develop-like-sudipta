#!/usr/bin/env bash
# Eval: every script in scripts/ (bridge) and hooks/scripts/ (hooks) must
# have at least one eval that references its basename. Threshold: ≥80%.
#
# Why: there are ~35 scripts and ~30 evals. The script-to-eval mapping was
# opaque before this gate — a regression in (say) lock.sh could ship with
# every existing eval green, because no eval mentioned lock.sh at all.
# This gate makes the gap measurable. A future script that lands without
# at least one referencing eval pushes coverage below 80% and trips the
# eval RED, prompting a smoke eval to be added.
#
# Allowlist: a small set of scripts are exempt because their correctness
# emerges from any eval that consumes their output, or they're presentation-
# only wrappers around content that's already tested elsewhere. Each
# exempt entry carries a one-line WHY.
#
# Side effect: regenerates SCRIPT_COVERAGE.md in the same directory so the
# matrix snapshot stays current. Running the eval mutates the working
# tree by exactly that one file; git diff reveals coverage drift.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SCRIPTS_DIR="$SCRIPT_DIR/../scripts"
HOOKS_DIR="$SCRIPT_DIR/../../../hooks/scripts"
EVALS_DIR="$SCRIPT_DIR"
SNAPSHOT="$SCRIPT_DIR/SCRIPT_COVERAGE.md"
THRESHOLD=80   # percent

# Allowlist — exempt-from-direct-coverage with one-line WHY per entry.
# Add sparingly; the bar is "direct testing is conceptually wrong or
# redundant", not "writing a test is hard".
ALLOWLIST=(
  # read_history.sh: pure osascript wrapper around Terminal history; no
  # branching logic. Mirrors read.sh. Correctness emerges from any eval
  # whose assertion consumes scrollback output.
  read_history.sh
  # audit_danger_patterns.sh: produces a markdown coverage report over
  # danger_patterns.txt. Match semantics are identical to what
  # test_danger_patterns.sh already exercises against the same fixture
  # set — testing the report wrapper separately would be redundant.
  audit_danger_patterns.sh
)

is_allowlisted() {
  local s="$1"
  for a in "${ALLOWLIST[@]}"; do
    [ "$s" = "$a" ] && return 0
  done
  return 1
}

# Eval files to grep — EXCLUDE self so the matrix's own allowlist + variable
# names don't false-positive cover any script that just happens to share a
# substring with this eval's source.
EVAL_FILES=$(ls "$EVALS_DIR"/test_*.sh | grep -v 'test_script_eval_coverage\.sh' || true)

# Enumerate scripts (basename-only, deduplicated, sorted).
ALL_SCRIPTS=$(for f in "$SCRIPTS_DIR"/*.sh "$HOOKS_DIR"/*.sh; do
  [ -f "$f" ] && basename "$f"
done | sort -u)

TOTAL=0
COVERED=0
EXEMPT=0
UNCOVERED_LIST=""

# Build the matrix rows in memory; emit to snapshot below.
ROWS=$(mktemp)
trap 'rm -f "$ROWS"' EXIT

while IFS= read -r s; do
  [ -z "$s" ] && continue
  if is_allowlisted "$s"; then
    EXEMPT=$((EXEMPT+1))
    printf '| `%s` | exempt | (allowlisted — see eval source for WHY) |\n' "$s" >> "$ROWS"
    continue
  fi
  TOTAL=$((TOTAL+1))
  # Find evals that reference this script's basename. Use -F (fixed string)
  # to avoid regex surprises; basenames can contain dots that would be
  # wildcards in -E mode.
  refs=""
  for ef in $EVAL_FILES; do
    if grep -qF "$s" "$ef" 2>/dev/null; then
      refs="$refs, $(basename "$ef")"
    fi
  done
  refs="${refs#, }"   # trim leading ", "
  if [ -n "$refs" ]; then
    COVERED=$((COVERED+1))
    printf '| `%s` | ✓ | %s |\n' "$s" "$refs" >> "$ROWS"
  else
    UNCOVERED_LIST="$UNCOVERED_LIST $s"
    printf '| `%s` | ✗ | — |\n' "$s" >> "$ROWS"
  fi
done <<< "$ALL_SCRIPTS"

# Percent + gate-required count.
if [ "$TOTAL" -gt 0 ]; then
  PCT=$(python3 -c "print(round($COVERED / $TOTAL * 100, 1))")
else
  PCT="0.0"
fi
REQUIRED=$(( TOTAL * THRESHOLD / 100 ))

# Write snapshot — single source of truth for "current coverage state".
{
  echo "# Script eval coverage matrix"
  echo
  echo "_Generated by \`test_script_eval_coverage.sh\` — running the eval refreshes this file. Do not hand-edit._"
  echo
  echo "**Coverage:** $COVERED / $TOTAL scripts have ≥1 referencing eval (**$PCT%**, threshold ≥${THRESHOLD}%, required ≥$REQUIRED)."
  echo "**Exempt:** $EXEMPT script(s) allowlisted (see eval source for per-script WHY)."
  echo
  echo "## Per-script coverage"
  echo
  echo "| Script | Has eval? | Referenced by |"
  echo "|---|---|---|"
  cat "$ROWS"
} > "$SNAPSHOT"

# Gate decision.
if [ "$COVERED" -lt "$REQUIRED" ]; then
  echo "FAIL: coverage $PCT% below ${THRESHOLD}% threshold ($COVERED / $TOTAL, need ≥$REQUIRED)"
  echo "  uncovered scripts:"
  for s in $UNCOVERED_LIST; do echo "    $s"; done
  echo
  echo "  matrix refreshed at $SNAPSHOT"
  exit 1
fi

echo "PASS  ($COVERED / $TOTAL = $PCT% ≥ ${THRESHOLD}%, exempt=$EXEMPT)"
